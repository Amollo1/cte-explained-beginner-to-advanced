DROP TABLE IF EXISTS customers_clean, salary_log, order_items_archive, orders_archive, customers_raw, bom, parts, routes,
                     order_items, orders, products, categories, customers, employees, departments CASCADE;

CREATE TABLE departments (
    dept_id INT PRIMARY KEY,
    dept_name TEXT NOT NULL,
    location TEXT
);

CREATE TABLE employees (
    emp_id INT PRIMARY KEY,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    job_title TEXT,
    dept_id INT REFERENCES departments(dept_id),
    manager_id INT REFERENCES employees(emp_id),
    salary NUMERIC(10,2),
    hire_date DATE
);

CREATE TABLE customers (
    customer_id INT PRIMARY KEY,
    customer_name TEXT NOT NULL,
    country TEXT,
    segment TEXT,
    signup_date DATE
);

CREATE TABLE categories (
    category_id INT PRIMARY KEY,
    category_name TEXT NOT NULL,
    parent_id INT REFERENCES categories(category_id)
);

CREATE TABLE products (
    product_id INT PRIMARY KEY,
    product_name TEXT NOT NULL,
    category_id INT REFERENCES categories(category_id),
    unit_price NUMERIC(10,2)
);

CREATE TABLE orders (
    order_id INT PRIMARY KEY,
    customer_id INT REFERENCES customers(customer_id),
    order_date DATE,
    status TEXT,
    shipping_fee NUMERIC(6,2)
);

CREATE TABLE order_items (
    item_id INT PRIMARY KEY,
    order_id INT REFERENCES orders(order_id),
    product_id INT REFERENCES products(product_id),
    quantity INT,
    discount NUMERIC(3,2)
);

CREATE TABLE routes (
    route_id INT PRIMARY KEY,
    origin TEXT NOT NULL,
    destination TEXT NOT NULL,
    distance_km INT
);

CREATE TABLE parts (
    part_id INT PRIMARY KEY,
    part_name TEXT NOT NULL,
    unit_cost NUMERIC(10,2)
);

CREATE TABLE bom (
    assembly_id INT REFERENCES parts(part_id),
    component_id INT REFERENCES parts(part_id),
    qty INT NOT NULL,
    PRIMARY KEY (assembly_id, component_id)
);

CREATE TABLE customers_raw (
    raw_id INT PRIMARY KEY,
    full_name TEXT,
    email TEXT,
    loaded_at TIMESTAMP
);

